<?php
declare(strict_types=1);

namespace WPCalibrate\MerchantFeedManager\Generator;

use WPCalibrate\MerchantFeedManager\Feed\FeedModel;
use WPCalibrate\MerchantFeedManager\Feed\FeedRepository;
use WPCalibrate\MerchantFeedManager\Feed\FeedRunModel;
use WPCalibrate\MerchantFeedManager\Feed\FeedRunRepository;
use WPCalibrate\MerchantFeedManager\Product\ProductQuery;
use WPCalibrate\MerchantFeedManager\Scheduler\ActionSchedulerService;
use WPCalibrate\MerchantFeedManager\Support\Logger;
use WPCalibrate\MerchantFeedManager\Validation\IssueRepository;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * High-level service to orchestrate and initiate product feed generation runs.
 */
class FeedGenerator {

	/**
	 * Start a feed generation run.
	 *
	 * @param int  $feed_id Feed ID.
	 * @param bool $async Whether to process asynchronously via Action Scheduler.
	 * @return array{success: bool, message: string, run_token?: string, run_id?: int}
	 */
	public static function start_generation( int $feed_id, bool $async = true ): array {
		$feed = FeedRepository::get_by_id( $feed_id );
		if ( ! $feed ) {
			return [
				'success' => false,
				'message' => __( 'Feed not found.', 'wpcalibrate-merchant-feed-manager' ),
			];
		}

		$run_token = wp_generate_password( 24, false );

		// 1. Try to acquire lock
		if ( ! GenerationLock::acquire( $feed_id, $run_token ) ) {
			return [
				'success' => false,
				'message' => __( 'Feed is currently being generated by another process. Please wait.', 'wpcalibrate-merchant-feed-manager' ),
			];
		}

		// 2. Clear old issue history for this feed to maintain fresh health stats
		IssueRepository::delete_by_feed( $feed_id );

		// 3. Count candidate products
		$total_products = ProductQuery::get_total_product_count();

		// 4. Create new run record
		$run                 = new FeedRunModel();
		$run->feed_id        = $feed->id;
		$run->run_token      = $run_token;
		$run->status         = 'generating';
		$run->current_offset = 0;
		$run->total_products = $total_products;
		$run->started_at     = current_time( 'mysql', true );

		$run_id = FeedRunRepository::insert( $run );
		if ( 0 === $run_id ) {
			GenerationLock::release( $feed_id, $run_token );
			return [
				'success' => false,
				'message' => __( 'Failed to initialize feed run in database.', 'wpcalibrate-merchant-feed-manager' ),
			];
		}

		// Update feed last_status
		$feed->last_status = 'generating';
		FeedRepository::update( $feed );

		Logger::info(
			'Initiated feed generation run',
			[
				'feed_id'        => $feed_id,
				'run_id'         => $run_id,
				'run_token'      => $run_token,
				'total_products' => $total_products,
				'async'          => $async,
			]
		);

		// 5. Dispatch
		if ( $async && ActionSchedulerService::is_available() ) {
			ActionSchedulerService::queue_generation( $feed_id, $run_token );
			return [
				'success'   => true,
				'message'   => __( 'Feed generation queued successfully in background.', 'wpcalibrate-merchant-feed-manager' ),
				'run_token' => $run_token,
				'run_id'    => $run_id,
			];
		}

		// Synchronous loop (fallback or CLI/tests)
		$max_iterations = 1000;
		$iterations     = 0;

		while ( $iterations < $max_iterations ) {
			$iterations++;
			$res = BatchProcessor::process_batch( $feed_id, $run_token );

			$current_run = FeedRunRepository::get_by_id( $run_id );
			if ( ! $current_run || in_array( $current_run->status, [ 'completed', 'completed_with_warnings', 'failed' ], true ) ) {
				break;
			}
		}

		return [
			'success'   => true,
			'message'   => __( 'Feed generation completed.', 'wpcalibrate-merchant-feed-manager' ),
			'run_token' => $run_token,
			'run_id'    => $run_id,
		];
	}
}
